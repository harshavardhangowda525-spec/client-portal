import { test, expect } from "@playwright/test";
// Voice requests with Chromium's fake microphone; needs the app running against e2e/mock-groq.mjs (E2E_GROQ_MOCK=1).
test.skip(process.env.E2E_GROQ_MOCK !== "1", "needs the app running against e2e/mock-groq.mjs");
test.use({ launchOptions: { executablePath: process.env.PW_CHROMIUM_PATH, args: ["--use-fake-ui-for-media-stream", "--use-fake-device-for-media-stream"] }, permissions: ["microphone"] });
test("voice recorder records, transcribes via Groq mock and fills the transcript", async ({ browser }) => {
  const admin = await (await browser.newContext({ permissions: ["microphone"] })).newPage();
  await admin.goto("/login");
  await admin.getByLabel("Email").fill("admin@infinity.test"); await admin.getByLabel("Password").fill("AdminPass2026");
  await admin.getByRole("button", { name: "Sign in" }).click();
  await expect(admin).toHaveURL(/\/admin$/);
  await admin.goto("/admin/clients/new");
  const s = Date.now().toString(36);
  await admin.getByLabel("Business name").fill(`Voice Co ${s}`); await admin.getByLabel("Owner name").fill("Vani"); await admin.getByLabel("Email").fill(`vani-${s}@example.test`);
  await admin.getByRole("button", { name: "Create client" }).click();
  await expect(admin).toHaveURL(/\/admin\/clients\/[0-9a-f-]{36}$/);
  await admin.getByLabel("Project name").fill("Voice Site"); await admin.getByRole("button", { name: "Create project" }).click();
  await expect(admin).toHaveURL(/\/admin\/projects\/[0-9a-f-]{36}$/);
  const pid = admin.url().split("/").pop();
  await admin.goBack();
  await admin.getByRole("button", { name: "Create invitation link" }).click();
  const invite = (await admin.locator("code").filter({ hasText: "/invite/" }).textContent())!.trim();
  const client = await (await browser.newContext({ permissions: ["microphone"] })).newPage();
  await client.goto(invite.replace(/^https?:\/\/[^/]+/, ""));
  await client.getByLabel("Create a password").fill("VoiceCo2026"); await client.getByLabel("Confirm password").fill("VoiceCo2026");
  await client.getByRole("button", { name: /Create account/ }).click();
  await expect(client).toHaveURL(/\/portal\/[0-9a-f-]{36}$/);
  await client.goto(`/portal/${pid}/resolve?tab=voice`);
  await client.waitForLoadState("networkidle");
  await client.getByRole("button", { name: "Start recording" }).click();
  await expect(client.getByRole("button", { name: "Stop" })).toBeVisible();
  await client.waitForTimeout(2500);
  await client.getByRole("button", { name: "Stop" }).click();
  await expect(client.getByLabel("Your recording")).toBeVisible();
  await client.getByLabel(/Keep my recording/).check();
  await client.getByRole("button", { name: "Transcribe" }).click();
  await expect(client.getByLabel("Transcript")).toHaveValue(/replace the hero background image/);
  await client.getByLabel("Transcript").fill("Please replace the hero background image with our new photo, on the homepage.");
  await client.getByRole("button", { name: "Send to the assistant" }).click();
  await expect(client).toHaveURL(/\/resolve\/[0-9a-f-]{36}$/);
  await expect(client.getByText(/voice transcript/)).toBeVisible();
  await expect(client.getByLabel("voice-note.webm")).toBeVisible();
});
